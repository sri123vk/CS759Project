#!/usr/bin/env python3
"""Fit the cost model behind `--impl auto` (src/dispatch.cpp).

Usage: fit_dispatch.py RESULTS_DIR [RESULTS_DIR ...] [-o include/dispatch_model.h]
                       [--report plots/<name>/dispatch.md]

For every implementation that appears in the runs' baseline.csv and
channels.csv, fits the median time of one call as

    t_ms = c0 + c1 * N*C + c2 * N + c3 * N*C*K^2        (N = H*W)

  c0    fixed cost per call (thread start-up, kernel launch, copy latency)
  c1    cost per input element (reading the input; the host->device copy)
  c2    cost per output element (writing the output; the device->host copy)
  c3    cost per multiply-add

with non-negative coefficients, minimising the relative error (so that
16x16 images count as much as 2048x2048 ones). OpenMP rows are taken at the
largest thread count with the static schedule, CUDA rows at the 32x8 block,
i.e. the settings `--impl auto` runs with. Rows that failed their
correctness check are left out.

Writes the coefficients as a C++ header and a report of how well the model
picks: for every measured workload, the implementation the model chooses
against the one that was actually fastest, and how much slower the choice is.
"""
import argparse
import datetime
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.optimize import nnls

CPU = ["seq", "omp", "omp_simd", "omp_blocked", "omp_tiled"]
GPU = ["cuda", "cuda_opt", "cuda_const", "cuda_tiled_const", "cuda_multiout",
       "cuda_multiout_const", "cuda_multiout_tiled", "cuda_multiout_tiled_const"]
CONSTANT = {"cuda_const", "cuda_tiled_const", "cuda_multiout_const", "cuda_multiout_tiled_const"}


def load(dirs):
    frames = []
    for d in dirs:
        for name in ("baseline.csv", "channels.csv"):
            f = Path(d) / name
            if f.exists():
                frames.append(pd.read_csv(f).assign(source=f"{Path(d).name}/{name}"))
    if not frames:
        sys.exit("no baseline.csv or channels.csv in " + ", ".join(map(str, dirs)))
    df = pd.concat(frames, ignore_index=True)
    if "C" not in df:
        df["C"] = 1
    df = df[df["pass"] == 1]
    df = df[df.impl.isin(CPU + GPU)].copy()

    omp = df.impl.str.startswith("omp")
    tmax = df.loc[omp, "threads"].max() if omp.any() else 1
    keep = (df.impl == "seq") \
        | (omp & (df.threads == tmax) & (df.schedule.fillna("static") == "static")) \
        | (df.impl.isin(GPU) & (df.bx == 32) & (df.by == 8))
    df = df[keep]
    # One time per (impl, workload): the median over repeated rows.
    df = df.groupby(["impl", "H", "W", "K", "C"], as_index=False).median_ms.median()
    return df, int(tmax)


def features(d):
    n = d.H.astype(float) * d.W
    return np.column_stack([np.ones(len(d)), n * d.C, n, n * d.C * d.K ** 2])


def fit(df):
    models = {}
    for impl, g in df.groupby("impl"):
        if len(g) < 6:
            continue
        x = features(g)
        y = g.median_ms.to_numpy()
        coef, _ = nnls(x / y[:, None], np.ones(len(y)))  # relative error
        pred = x @ coef
        models[impl] = dict(coef=coef, n=len(g),
                            med_err=float(np.median(np.abs(pred / y - 1))),
                            max_err=float(np.max(np.abs(pred / y - 1))))
    return models


def allowed(impl, C, K):
    return impl not in CONSTANT or C * K * K <= 4096


def evaluate(df, models):
    """Model's pick vs the measured fastest, over workloads that have every model's impl."""
    rows = []
    for (H, W, K, C), g in df.groupby(["H", "W", "K", "C"]):
        g = g[g.impl.isin(models)]
        g = g[[allowed(i, C, K) for i in g.impl]]
        if g.empty:
            continue
        n = float(H) * W
        pred = {i: float(np.array([1, n * C, n, n * C * K * K]) @ models[i]["coef"]) for i in g.impl}
        pick = min(pred, key=pred.get)
        best = g.loc[g.median_ms.idxmin()]
        t_pick = float(g.loc[g.impl == pick, "median_ms"].iloc[0])
        rows.append(dict(H=H, W=W, K=K, C=C, pick=pick, fastest=best.impl,
                         slowdown=t_pick / best.median_ms))
    return pd.DataFrame(rows)


def header(models, dirs, tmax, out):
    lines = [
        "// Cost model for conv2d_choose (src/dispatch.cpp).",
        f"// Generated by scripts/fit_dispatch.py on {datetime.date.today()} from:",
        *[f"//   {d}" for d in dirs],
        "// Regenerate after a new benchmark run; do not edit by hand.",
        "//",
        "// t_ms = c0 + c1*N*C + c2*N + c3*N*C*K*K, N = H*W. OpenMP rows at",
        f"// {tmax} threads (static schedule), CUDA rows at the 32x8 block,",
        "// end-to-end (copies included).",
        "#pragma once",
        "",
        "struct DispatchModel {",
        "    const char* impl;",
        "    bool gpu;",
        "    double c0, c1, c2, c3;",
        "};",
        "",
        f"constexpr int kDispatchThreads = {tmax};",
        "",
        "constexpr DispatchModel kDispatchModels[] = {",
    ]
    for impl, m in sorted(models.items(), key=lambda kv: (kv[0] in GPU, kv[0])):
        c = m["coef"]
        lines.append(f'    {{"{impl}", {str(impl in GPU).lower()}, '
                     f'{c[0]:.6e}, {c[1]:.6e}, {c[2]:.6e}, {c[3]:.6e}}},'
                     f'  // {m["n"]} rows, median error {100 * m["med_err"]:.0f}%')
    lines += ["};", ""]
    Path(out).write_text("\n".join(lines), encoding="utf-8")


def report(models, ev, dirs, tmax, out):
    p = ["# Dispatcher cost model", "",
         "Data: " + ", ".join(f"`{d}`" for d in dirs) +
         f". OpenMP at {tmax} threads, static; CUDA end-to-end at 32x8.", "",
         "## Fit per implementation", "",
         "| impl | rows | median error | max error | c0 (ms) | per input elem (ns) | per output elem (ns) | per MAC (ps) |",
         "|---|---|---|---|---|---|---|---|"]
    for impl, m in sorted(models.items(), key=lambda kv: (kv[0] in GPU, kv[0])):
        c = m["coef"]
        p.append(f"| {impl} | {m['n']} | {100 * m['med_err']:.0f}% | {100 * m['max_err']:.0f}% | "
                 f"{c[0]:.4f} | {c[1] * 1e6:.3f} | {c[2] * 1e6:.3f} | {c[3] * 1e9:.3f} |")
    if not ev.empty:
        exact = (ev.pick == ev.fastest).mean()
        within = (ev.slowdown <= 1.10).mean()
        p += ["", "## Picks", "",
              f"{len(ev)} workloads. The model picks the fastest implementation in "
              f"{100 * exact:.0f}% of them and one within 10% of the fastest in {100 * within:.0f}%. "
              f"Worst case: {ev.slowdown.max():.2f}x the fastest time; "
              f"geometric mean {np.exp(np.log(ev.slowdown).mean()):.3f}x.", "",
              "| H | W | K | C | picked | fastest | picked / fastest |", "|---|---|---|---|---|---|---|"]
        for r in ev.sort_values(["C", "K", "H"]).itertuples():
            p.append(f"| {r.H} | {r.W} | {r.K} | {r.C} | {r.pick} | {r.fastest} | {r.slowdown:.2f} |")
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(p) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("dirs", nargs="+")
    ap.add_argument("-o", "--out", default="include/dispatch_model.h")
    ap.add_argument("--report")
    a = ap.parse_args()
    df, tmax = load(a.dirs)
    models = fit(df)
    ev = evaluate(df, models)
    header(models, a.dirs, tmax, a.out)
    print(f"{a.out}: {len(models)} implementations")
    if a.report:
        report(models, ev, a.dirs, tmax, a.report)
        print(a.report)
    if not ev.empty:
        print(f"picks fastest in {100 * (ev.pick == ev.fastest).mean():.0f}% of {len(ev)} workloads, "
              f"within 10% in {100 * (ev.slowdown <= 1.10).mean():.0f}%, worst {ev.slowdown.max():.2f}x")


if __name__ == "__main__":
    main()
